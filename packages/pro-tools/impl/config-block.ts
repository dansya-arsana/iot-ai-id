/**
 * CONFIG block generator and injector (arch §3.5). Every code file starts with a generated block between the markers; the model's
 * own text between the markers is overwritten. The block holds pins, thresholds, NODE_ID, LORA_FREQ_HZ, placeholders and the
 * AIOT_BOOT_BANNER that code-lint requires to be printed in setup (M7 reads it as flash evidence).
 */
import {createHash} from 'node:crypto';
import {LORA_BAND} from '../data/radio.js';
import type {PinRow} from './allocate.js';

export const CONFIG_BEGIN='==== CONFIG (generated by iot.ai.id: pins and thresholds) ====';
export const CONFIG_END='==== END CONFIG ====';
export const BANNER_SYMBOL='AIOT_BOOT_BANNER';
export const BANNER_PREFIX='AIOT_BOOT';
const SYM_RE=/^[A-Z][A-Z0-9_]{0,31}$/;
const sha=(s:string)=>createHash('sha256').update(s).digest('hex');

export type ConfigInput={
 language:'arduino-cpp'|'micropython'|'python';nodeId:string;pins:PinRow[];
 thresholds?:Record<string,number>;sampleEveryS?:number;loraFreqMHz?:number;wifi?:boolean;mqttTopicPrefix?:string;
};
export type ConfigBlock={block:string;sha256:string;banner:string;symbols:Record<string,string>};

const pinLiteral=(boardPin:string,gpio:number|null):string=>/^A\d+$/.test(boardPin)?boardPin:gpio!==null?String(gpio):boardPin;
const comment=(py:boolean)=>py?'#':'//';

export function buildConfigBlock(c:ConfigInput):ConfigBlock{
 const py=c.language!=='arduino-cpp',cm=comment(py);
 if(!/^[a-z][a-z0-9-]{0,31}$/.test(c.nodeId))throw new Error('bad nodeId');
 const def=(name:string,val:string|number,note?:string)=>py?`${name} = ${val}${note?`  # ${note}`:''}`:`#define ${name} ${val}${note?` // ${note}`:''}`;
 const q=(s:string)=>JSON.stringify(s);
 const body:string[]=[];
 body.push(def('NODE_ID',q(c.nodeId)));
 const symbols:Record<string,string>={};
 for(const p of c.pins){
  if(!p.symbol)continue;
  if(!SYM_RE.test(p.symbol))throw new Error(`bad symbol ${p.symbol}`);
  if(p.symbol in symbols)throw new Error(`duplicate symbol ${p.symbol}`);
  symbols[p.symbol]=p.boardPin;
  body.push(def(p.symbol,pinLiteral(p.boardPin,p.gpio),`${p.boardPin} ${p.part}.${p.partPin}`));
 }
 for(const [k,v] of Object.entries(c.thresholds??{})){
  if(!SYM_RE.test(k)||!Number.isFinite(v))throw new Error(`bad threshold ${k}`);
  body.push(def(k,v));
 }
 body.push(def('SAMPLE_EVERY_S',c.sampleEveryS??60));
 if(c.loraFreqMHz!==undefined){
  if(c.loraFreqMHz<LORA_BAND.minMHz||c.loraFreqMHz>LORA_BAND.maxMHz)throw new Error(`LoRa frequency ${c.loraFreqMHz} MHz is outside ${LORA_BAND.minMHz}-${LORA_BAND.maxMHz} MHz`);
  body.push(def('LORA_FREQ_HZ',Math.round(c.loraFreqMHz*1e6)));
 }
 if(c.wifi){body.push(def('WIFI_SSID',q('YOUR_WIFI_SSID')));body.push(def('WIFI_PASSWORD',q('YOUR_WIFI_PASSWORD')));}
 const core=body.join('\n');
 const banner=`${BANNER_PREFIX}:${c.nodeId}:${sha(core).slice(0,8)}`;
 const lines=[`${cm} ${CONFIG_BEGIN}`,...body,def(BANNER_SYMBOL,q(banner)),`${cm} ${CONFIG_END}`];
 const block=lines.join('\n')+'\n';
 return {block,sha256:sha(block),banner,symbols};
}

/** Replace everything between the markers (or prepend the block when the file has none). Never trusts the model's CONFIG text. */
export function injectConfigBlock(source:string,block:string,language:ConfigInput['language']='arduino-cpp'):string{
 const cm=comment(language!=='arduino-cpp');
 const isBegin=(l:string)=>l.trim().startsWith(cm)&&l.includes('==== CONFIG (');
 const isEnd=(l:string)=>l.trim().startsWith(cm)&&l.includes(CONFIG_END);
 const lines=source.split('\n'),blockLines=block.replace(/\n$/,'').split('\n'),out:string[]=[];
 let placed=false;
 for(let i=0;i<lines.length;){
  const l=lines[i]!;
  if(isBegin(l)){
   const j=lines.findIndex((x,k)=>k>i&&isEnd(x));
   if(j<0){i++;continue;}                                   // unterminated begin marker: drop it
   if(!placed){out.push(...blockLines);placed=true;}        // later duplicate blocks are dropped
   i=j+1;continue;
  }
  if(isEnd(l)){i++;continue;}                               // stray end marker
  out.push(l);i++;
 }
 return placed?out.join('\n'):block+out.join('\n');
}
/** Hash of the injected block as stored in the code file. */
export const configShaOf=(block:string):string=>sha(block);
export const sha256Hex=sha;
