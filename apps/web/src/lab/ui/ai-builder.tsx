import './ai-builder.css';
import {useCallback,useEffect,useMemo,useRef,useState} from 'react';
import {Link} from 'react-router-dom';
import {useLang} from '../../i18n';
import {memberAuth} from '../../ops-client';
import {LAB_AI_DAILY_MEMBER_QUOTA,LAB_AI_PROMPT_MAX} from '../../../../../packages/ops-contract';
import type {CircuitSpec,SpecStep} from '../circuit-spec';
import {AI_PHASES,AiBuildError,PHASE_COPY,aiClient,chipText} from '../ai/client';
import type {AiBuild,AiExample,AiIssue,AiPhase} from '../ai/client';

/** The slice of LabSceneV3 this panel needs; the integrator passes the real scene. */
export interface AssemblyScene{playAssembly(spec:CircuitSpec,o?:{onStep?(e:{index:number;total:number;step:SpecStep;phase:'start'|'end'}):void;speed?:number;signal?:AbortSignal}):Promise<void>;loadCircuit(spec:CircuitSpec):void}
type Stage='idle'|'building'|'assembling'|'ready'|'error';
type Access='unknown'|'anon'|'member';

export function AiBuildButton({onClick,active}:{onClick:()=>void;active?:boolean}){
 const {tr}=useLang();
 return <button type="button" className="aib-entry" data-testid="lab-ai-open" aria-pressed={active} onClick={onClick}><span aria-hidden="true">+</span> {tr('Build with AI','Bangun dengan AI')}</button>;
}

/** Chip for the code view: shown while the sketch on screen is the AI-generated one. */
export function AiGeneratedChip({build,short}:{build:AiBuild;short?:boolean}){
 const {tr}=useLang();
 return <span className="aib-chip" data-testid="lab-ai-chip" title={`${tr('compiled with','dikompilasi dengan')} ${build.build.toolchain}`}>{tr('Generated by AI','Dibuat oleh AI')}{short?'':` · ${chipText(build)}`}</span>;
}

const fmtIssue=(i:AiIssue,lang:'en'|'id')=>lang==='id'?i.id:i.en;

export function AiBuilder({scene,onBuilt,onRun,onClose}:{
 scene:AssemblyScene|null;
 /** Called once the firmware is ready: load the hex into the runner and show spec.sketch.source read-only (with AiGeneratedChip). */
 onBuilt:(b:AiBuild)=>void;
 /** Assembly finished (or skipped) and the user pressed Run. */
 onRun:(b:AiBuild)=>void;
 onClose?:()=>void;
}){
 const {tr,lang}=useLang();
 const [prompt,setPrompt]=useState('');
 const [access,setAccess]=useState<Access>('unknown');
 const [examples,setExamples]=useState<AiExample[]>([]);
 const [exampleErr,setExampleErr]=useState(false);
 const [stage,setStage]=useState<Stage>('idle');
 const [phase,setPhase]=useState<AiPhase>('designing');
 const [err,setErr]=useState<AiBuildError|null>(null);
 const [needSignin,setNeedSignin]=useState(false);
 const [build,setBuild]=useState<AiBuild|null>(null);
 const [step,setStep]=useState<{index:number;total:number;step:SpecStep}|null>(null);
 const ctl=useRef<AbortController|null>(null);
 const reduced=useMemo(()=>typeof matchMedia==='function'&&matchMedia('(prefers-reduced-motion: reduce)').matches,[]);

 useEffect(()=>{
  let live=true;
  memberAuth.me().then(m=>{if(live)setAccess(m.grants.includes('lab-ai')?'member':'anon');}).catch(()=>{if(live)setAccess('anon');});
  aiClient.examples().then(e=>{if(live)setExamples(e);}).catch(()=>{if(live)setExampleErr(true);});
  return()=>{live=false;ctl.current?.abort();};
 },[]);

 const assemble=useCallback(async(b:AiBuild,speed=1)=>{
  if(!scene)return;
  ctl.current?.abort();
  const c=new AbortController();ctl.current=c;
  setStage('assembling');setPhase('assembling');setStep(null);
  try{
   await scene.playAssembly(b.spec,{speed:reduced?0:speed,signal:c.signal,onStep:e=>{if(e.phase==='start')setStep({index:e.index,total:e.total,step:e.step});}});
   setStage('ready');
  }catch(e){if((e as Error).name!=='AbortError')setStage('ready');}
 },[scene,reduced]);

 const finish=useCallback((b:AiBuild)=>{setBuild(b);onBuilt(b);return assemble(b);},[onBuilt,assemble]);
 const sleep=(ms:number)=>reduced?Promise.resolve():new Promise<void>(r=>setTimeout(r,ms));

 const runExample=async(ex:AiExample)=>{
  setPrompt(ex.prompt[lang]);setErr(null);setNeedSignin(false);
  ctl.current?.abort();
  const b:AiBuild={buildId:`ex-${ex.exampleId}`,source:'example',spec:ex.spec,build:ex.build,issues:[],repaired:false};
  setStage('building');setPhase('assembling');
  await finish(b);
 };

 const submit=async()=>{
  const text=prompt.trim();
  if(text.length<8)return;
  if(access!=='member'){setNeedSignin(true);return;}
  setNeedSignin(false);setErr(null);setStep(null);
  ctl.current?.abort();const c=new AbortController();ctl.current=c;
  setStage('building');setPhase('designing');
  try{
   // One request covers design, validation and compile; the server answers once. The later phases are shown from the real response (repaired, source, bytes).
   const b=await aiClient.build(text,lang,c.signal);
   setPhase('checking');await sleep(280);
   setPhase('compiling');await sleep(280);
   setBuild(b);onBuilt(b);
   await assemble(b);
  }catch(e){
   if((e as Error).name==='AbortError')return;
   setErr(e instanceof AiBuildError?e:new AiBuildError('Something went wrong','unavailable'));setStage('error');
  }
 };

 const skip=()=>{ctl.current?.abort();if(build)scene?.loadCircuit(build.spec);setStage('ready');setStep(null);};
 const replay=()=>{if(build)void assemble(build,1);};
 const busy=stage==='building'||stage==='assembling';
 const errText=(e:AiBuildError)=>{
  switch(e.kind){
   case 'quota':return tr('You have used today\'s builds. Try again tomorrow.','Jatah build hari ini sudah habis. Coba lagi besok.');
   case 'forbidden':case 'signin':return tr('Building from your own text is for members.','Membuat dari teks sendiri khusus anggota.');
   case 'validation':return tr('The design did not pass the wiring check, even after a retry. Try rewording it.','Rancangan belum lolos pemeriksaan kabel, bahkan setelah dicoba ulang. Coba ubah kalimatnya.');
   case 'compile':return tr('The generated code did not compile. Try rewording it.','Kode yang dibuat tidak bisa dikompilasi. Coba ubah kalimatnya.');
   case 'network':return tr('Could not reach the build service.','Layanan build tidak terjangkau.');
   case 'bad-request':return tr('Please describe the build in a bit more detail.','Jelaskan rangkaiannya sedikit lebih rinci.');
   default:return tr('The AI builder is unavailable right now.','Pembuat AI sedang tidak tersedia.');
  }
 };
 const idx=step?.index??0,total=step?.total??0;

 return (
  <section className="aib" data-testid="lab-ai" data-stage={stage} aria-label={tr('Describe your build','Jelaskan rangkaianmu')}>
   <header className="aib-head">
    <span className="lab-eyebrow">{tr('Build with AI','Bangun dengan AI')}</span>
    {onClose&&<button type="button" className="lab-x" aria-label={tr('Close','Tutup')} onClick={onClose}>×</button>}
   </header>
   <label className="aib-label" htmlFor="aib-prompt">{tr('Describe your build','Jelaskan rangkaianmu')}</label>
   <textarea id="aib-prompt" className="aib-prompt" data-testid="lab-ai-prompt" rows={3} maxLength={LAB_AI_PROMPT_MAX} disabled={busy}
    placeholder={tr('I want an Arduino that beeps and lights red when something is closer than 20 cm','Saya mau Arduino yang berbunyi dan menyalakan lampu merah saat ada benda lebih dekat dari 20 cm')}
    value={prompt} onChange={e=>{setPrompt(e.target.value);setNeedSignin(false);}}
    onKeyDown={e=>{if(e.key==='Enter'&&(e.metaKey||e.ctrlKey)){e.preventDefault();void submit();}}}/>
   <div className="aib-row">
    <div className="aib-chips" role="list" aria-label={tr('Examples','Contoh')}>
     {examples.map(ex=><button key={ex.exampleId} type="button" role="listitem" className="aib-ex" data-testid={`lab-ai-ex-${ex.exampleId}`} disabled={busy||!scene} onClick={()=>void runExample(ex)}>{ex.prompt[lang]}</button>)}
     {exampleErr&&<span className="lab-muted">{tr('Examples are unavailable right now.','Contoh sedang tidak tersedia.')}</span>}
    </div>
    <button type="button" className="aib-go" data-testid="lab-ai-submit" disabled={busy||prompt.trim().length<8||!scene} onClick={()=>void submit()}>{tr('Build','Bangun')}</button>
   </div>
   {needSignin&&<p className="aib-note" role="status" data-testid="lab-ai-signin">
    <Link to="/masuk">{tr('Sign in to build your own','Masuk untuk membuat sendiri')}</Link>. {tr(`Members get ${LAB_AI_DAILY_MEMBER_QUOTA} builds a day. The three examples above are free for everyone and run instantly.`,`Anggota mendapat ${LAB_AI_DAILY_MEMBER_QUOTA} build per hari. Tiga contoh di atas gratis untuk semua dan langsung jalan.`)}
   </p>}
   {access==='anon'&&!needSignin&&stage==='idle'&&<p className="aib-hint lab-muted">{tr('Examples run instantly. Typing your own needs a member account.','Contoh langsung jalan. Mengetik sendiri butuh akun anggota.')}</p>}
   {stage==='building'&&build===null&&(
    <ol className="aib-phases" data-testid="lab-ai-phases" aria-live="polite">
     {AI_PHASES.map(p=>{const cur=AI_PHASES.indexOf(phase),me=AI_PHASES.indexOf(p);return <li key={p} data-state={me<cur?'done':me===cur?'now':'todo'}>{PHASE_COPY[p][lang]}</li>;})}
    </ol>
   )}
   {stage==='error'&&err&&(
    <div className="aib-err" role="alert" data-testid="lab-ai-error">
     <p>{errText(err)}</p>
     {err.issues.filter(i=>i.severity==='error').slice(0,4).map((i,k)=><p key={k} className="aib-issue">{fmtIssue(i,lang)}</p>)}
     {err.diagnostics.slice(0,3).map((d,k)=><p key={k} className="aib-issue aib-mono">{d.line>0?`L${d.line} `:''}{d.message}</p>)}
     {err.quota&&<p className="lab-muted">{err.quota.usedToday}/{err.quota.limit}</p>}
    </div>
   )}
   {(stage==='assembling'||stage==='ready')&&build&&(
    <div className="aib-rail" data-testid="lab-ai-rail">
     <div className="aib-rail-top">
      <span className="lab-eyebrow">{stage==='assembling'?(total?tr(`Step ${idx+1}/${total}`,`Langkah ${idx+1}/${total}`):tr('Assembling','Merakit')):tr('Assembled','Selesai dirakit')}</span>
      <AiGeneratedChip build={build}/>
     </div>
     <p className="aib-caption" aria-live="polite" data-testid="lab-ai-caption">{stage==='assembling'?(step?step.step.caption[lang]:''):(build.spec.goal?.[lang]??tr('Everything is in place.','Semua sudah terpasang.'))}</p>
     {build.issues.some(i=>i.severity==='warning')&&<p className="lab-muted">{build.issues.filter(i=>i.severity==='warning').slice(0,2).map(i=>fmtIssue(i,lang)).join(' ')}</p>}
     <div className="aib-actions">
      <button type="button" className="aib-btn" onClick={replay}>{tr('Replay','Ulangi')}</button>
      {stage==='assembling'&&<button type="button" className="aib-btn" data-testid="lab-ai-skip" onClick={skip}>{tr('Skip','Lewati')}</button>}
      <span className="lab-grow"/>
      <button type="button" className="aib-go" data-testid="lab-ai-run" disabled={stage!=='ready'} onClick={()=>onRun(build)}>{tr('Run','Jalankan')}</button>
     </div>
    </div>
   )}
  </section>
 );
}
