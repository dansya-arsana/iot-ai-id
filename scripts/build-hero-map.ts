/**
 * Generates apps/web/src/hero-map-data.ts: the region-tagged ~0.2° dot grid of the global home hero.
 * Input is Natural Earth (public domain) 1:10m admin-1 and admin-0 GeoJSON, read as data only:
 *   npx tsx scripts/build-hero-map.ts <dir with ne_10m_admin_1_states_provinces.geojson and ne_10m_admin_0_countries.geojson>
 * Source: https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ (raw GeoJSON is not committed).
 */
import {readFileSync,writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {rasterize,type Feature} from './hero-map-grid.js';

const dir=process.argv[2];
if(!dir){console.error('usage: tsx scripts/build-hero-map.ts <naturalearth dir>');process.exit(1);}
const load=(name:string)=>(JSON.parse(readFileSync(join(dir,name),'utf8')) as {features:Feature[]}).features;
const spec={lon0:94.8,lon1:144,lat0:-11.4,lat1:6.4,step:.2};
const {cols,rows,grid,unknown}=rasterize(load('ne_10m_admin_1_states_provinces.geojson'),load('ne_10m_admin_0_countries.geojson'),spec);
if(unknown.length)console.warn('unmapped Indonesian provinces:',unknown.join(', '));
const counts:Record<string,number>={};for(const ch of grid.join(''))if(ch!=='.')counts[ch]=(counts[ch]??0)+1;
writeFileSync('apps/web/src/hero-map-data.ts',`// Generated by scripts/build-hero-map.ts from Natural Earth 1:10m admin-1 and admin-0 (public domain). Do not edit.
// One string per row, one char per ${spec.step}° cell. Capitals: S Sumatra, B Kepri/Batam, J Java, K Kalimantan, L Sulawesi, N Bali & Nusa Tenggara, M Maluku, P Papua. Lower case: faint neighbours m Malaysia, b Brunei, p Papua New Guinea, t Timor-Leste, s Singapore.
export const heroGrid={lon0:${spec.lon0},lat1:${spec.lat1},step:${spec.step},cols:${cols},rows:${rows},grid:[
${grid.map(r=>`'${r}'`).join(',\n')}
]};
`);
console.log(`hero map: ${cols}x${rows} cells`,counts);
